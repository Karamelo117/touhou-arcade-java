    /**
     * Maneja el evento de clic en el botón "Registrar".
     * 
     * 1. Valida que los campos de texto no estén vacíos.
     * 2. Consulta la base de datos para verificar que el nombre de usuario no esté duplicado.
     * 3. Si no existe otro, genera una contraseña automática concatenando:
     *    - Primera letra del nombre en minúscula.
     *    - 3 dígitos numéricos aleatorios (0-9).
     *    - Primera letra del apellido en mayúscula.
     *    - Última letra del apellido en minúscula.
     *    - Un carácter especial aleatorio (#, ?, $, !, +, *).
     * 4. Instancia el nuevo Jugador, lo inserta en la base de datos mediante DAO y refresca la tabla.
     * 
     * @param evt Evento de acción disparado por el botón.
     */
    
    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        boolean existe = false, activo=false, lleno=true;
        String nombre = txtNombre.getText();
        String apellido = txtApellido.getText();
        String user = txtUsuario.getText();
        // Validación de campos vacíos
        if(nombre.equals("")||apellido.equals("")||user.equals("")){
        
            JOptionPane.showMessageDialog(null, "Es obligatorio llenar todos los campos");
            lleno=false;
            
        }
        
       // Validación de existencia previa del usuario en BD
       try{
       
           Connection cn = Conexion.conectar();
           String sql = "SELECT COUNT(*) FROM jugador WHERE user = ?";
           PreparedStatement ps = cn.prepareStatement(sql);
           ps.setString(1, user);
           
           ResultSet rs = ps.executeQuery();
           
           if(rs.next()){
               int contador = rs.getInt(1);
               if(contador>0){
                   existe=true;
               }
               else{
                   existe=false;
               }
           }
       
       }catch(Exception e){
           System.out.println("HUBO UN ERROR AL REALIZAR LA VERIFICACION: "+e);
       }
        
        
        // Proceso de generación de credenciales e inserción
        if(existe==false&&lleno==true){
        lblError.setText("");
        int aLen = apellido.length(), i;
        String parDos="", parCinco="";
        
       // Primera parte: Primera letra del nombre en minúscula
        String parUno = nombre.substring(0,1).toLowerCase();
        
       // Segunda parte: Tres dígitos aleatorios
        Random rand = new Random();
        for(i = 0; i<3; i++){
        
            int numD=0;
            numD = rand.nextInt(10);
            parDos += String.valueOf(numD);
        
        }
        
       // Tercera parte: Primera letra del apellido en mayúscula
       String parTres = apellido.substring(0,1).toUpperCase();
       
       // Cuarta parte: Última letra del apellido en minúscula
        String parCuatro = apellido.substring(aLen-1).toLowerCase();
        
        // Quinta parte: Carácter especial aleatorio
        int al = rand.nextInt(1,7);
        
        switch(al){
        
            case 1:
                parCinco = "#";
                break;
            case 2:
                parCinco = "?";
                break;
            case 3:
                parCinco = "$";
                break;
            case 4:
                parCinco = "!";
                break;
            case 5:
                parCinco = "+";
                break;
            case 6:
                parCinco = "*";
                break;
                
        }
        
        // Construcción final de la contraseña y guardado   
        String contrasena = parUno+parDos+parTres+parCuatro+parCinco;
        activo=true;
        Jugador nJug = new Jugador(nombre, apellido, user, contrasena, activo);
        JugadorDAO alta = new JugadorDAO();
        alta.altaJugador(nJug);
        JOptionPane.showMessageDialog(null, "Has sido exitosamente registrado\n Tu contrasena es: "+ contrasena);
        cargarTabla();
        }
        else{
        
          if(existe==true){
          lblError.setText("El nombre de usuario que escribiste ya esta en uso");
          }
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

