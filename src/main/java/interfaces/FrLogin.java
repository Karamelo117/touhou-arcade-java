    /**
     * Evento desencadenado al presionar el botón "Entrar".
     * Se encarga de validar que el usuario y la contraseña existan y coincidan 
     * en la base de datos antes de permitir el acceso al juego.
     * 
     */
    
    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        // Captura de los datos ingresados en los campos de texto
            String user = txtUser.getText();
            String pass = txtPass.getText();
            boolean valido = false;

        try {
            Connection cn = Conexion.conectar();
            
            /*
             * Se utiliza 'SELECT COUNT(*)' para obtener un valor numérico (0 o 1).
             * Si existe un registro con ese usuario Y esa contraseña exacta, devolverá 1.
             * Si las credenciales no existen o son incorrectas, devolverá 0.
             * El uso de 'PreparedStatement' (?) evita ataques de Inyección SQL.
             */
            
            String sql = "SELECT COUNT(*) FROM jugador WHERE user = ? AND pass = ?";
            PreparedStatement ps = cn.prepareStatement(sql);
            ps.setString(1, user);
            ps.setString(2, pass);

            ResultSet rs = ps.executeQuery();
            
            // Si la consulta arroja resultados y el valor del conteo es mayor a 0
            if (rs.next() && rs.getInt(1) > 0) {
                valido = true;
                // Se registra globalmente quién está jugando actualmente
                usuarioActual = user; // Guarda el usuario conectado
                }
            } catch (Exception e) {
                System.out.println("ERROR AL VALIDAR LOGIN: " + e);
            }
        // Resolución del inicio de sesión
        if (valido) {
            // Limpia el mensaje de error para que no aparezca nada si no sucedio un problema de verificacion
            lblError.setText("");
            // Instancia y despliega la ventana principal del juego
            FrJuego fr = new FrJuego();
            fr.setVisible(true);
            fr.setLocationRelativeTo(null);
            // Destruye y cierra la ventana actual de Login
            this.dispose();
        } else {
            // Si es inválido, notifica al usuario sin borrar los campos
            lblError.setText("El usuario o contraseña que escribiste es incorrecto");
        }
        
    
    }//GEN-LAST:event_btnLoginActionPerformed

